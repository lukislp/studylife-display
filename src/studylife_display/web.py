    # -- connecting ---------------------------------------------------------------------

    def connect_mode(self) -> tuple[str, str]:
        """("redirect", uri) with DISPLAY_PUBLIC_BASE_URL, ("paste", uri) otherwise."""
        public = self.settings.display_public_base_url
        if public:
            return "redirect", public_redirect_uri(public)
        return "paste", loopback_redirect_uri(parse_bind(self.settings.display_web_bind)[1])

    def pending(self) -> PendingConnect | None:
        """The attempt in progress, or None once it has expired."""
        with self._pending_lock:
            pending = self._pending
            if pending is not None and pending.expired(self.now()):
                self._pending = None
                return None
            return pending

    def begin_connect(self) -> PendingConnect:
        _, redirect_uri = self.connect_mode()
        pending = start_connect(str(self.settings.studylife_base_url), redirect_uri, self.now())
        with self._pending_lock:
            self._pending = pending
        log.info("connect attempt started (redirect_uri=%s)", redirect_uri)
        return pending

    def finish_connect(self, text: str) -> str:
        """Checks the callback (pasted or received), redeems the assertion and drops the
        key into the pending file. Returns the flash key; the attempt is consumed on any
        outcome but a missing assertion, so a URL cannot be tried twice."""
        try:
            result = parse_callback(text)
        except ConnectError as exc:
            return exc.key
        with self._pending_lock:
            pending = self._pending
            self._pending = None
        try:
            check_callback(pending, result, self.now())
            assert pending is not None
            api_key, user_id = exchange_assertion(
                str(self.settings.studylife_base_url), CLIENT_ID, result.assertion, pending.verifier
            )
        except ConnectError as exc:
            log.warning("connect attempt failed: %s", exc)
            self._flash_detail = exc.detail
            return exc.key
        try:
            write_pending_credentials(
                self.state_dir, api_key, str(self.settings.studylife_base_url), self.now()
            )
        except OSError as exc:
            log.error("could not write the pending credentials: %s", exc)
            self._flash_detail = str(exc)
            return "write_failed"
        log.info("API key obtained for user %s, handed to credentials-apply", user_id)
        return "applied"

    def identity_line(self) -> str:
        """What the connect page says about the stored key: nothing stored, or whoami's
        answer, or why it could not be obtained."""
        t = self.text
        instance = str(self.settings.studylife_base_url).rstrip("/")
        key = self.settings.studylife_api_key
        if not key:
            return t["connect_no_key"]
        try:
            who = whoami(instance, key, self.settings.http_timeout_seconds)
        except ConnectError as exc:
            template = t["connect_rejected"] if exc.key == "rejected" else t["connect_unreachable"]
            return template.format(instance=instance, detail=exc.detail)
        return t["connect_connected"].format(
            instance=instance, user_id=who.get("userId"), credential=who.get("credential")
        )

