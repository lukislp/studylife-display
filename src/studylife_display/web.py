"""The web interface: pages to pick a layout and refresh the panel, to connect the
StudyLife account and to change the settings, from a phone on the same network. Standard
library only (`http.server`), inline CSS, no external resources.

Security model, in one paragraph: the person installing chooses DISPLAY_WEB_TOKEN; `serve`
refuses to start without one of at least MIN_TOKEN_LENGTH characters. The login form posts
the token, which is compared in constant time; a wrong one costs a second and a 403. A right
one sets an HttpOnly, SameSite=Strict session cookie whose value is an HMAC of the token
under a key drawn at process start, so cookies die with the process and the token itself is
never stored in the browser. State-changing POSTs additionally require a same-origin
`Sec-Fetch-Site` or `Origin`. The layout pages never call the StudyLife API: previews are
drawn from the cached payloads (or sample data), and a refresh runs the same pipeline the
five-minute timer uses, under the panel lock. The connect page is the one exception: it
redeems the consent assertion and asks `/api/auth/whoami` whose key it holds (see
`connect.py`); the key it obtains goes into a 0600 file for the root-only apply unit and
is never sent to the browser.

`GET /current.png` (cookie required) is the frame that is on the panel right now, as
`main._put_on_panel` kept it. `GET /healthz` is outside that model: no cookie, no
same-origin check, a JSON summary of the panel's state for an uptime monitor. It carries no
secret - never the token, never the cookie - and never calls the StudyLife API.
`GET /connect/callback` is the other route without a cookie: the browser arriving there
comes from StudyLife's redirect (which never carries a SameSite=Strict cookie); the
single-use state generated by an authenticated request is what binds it to this display.
"""

