    def parse_settings_form(self, form: dict[str, str]) -> tuple[dict[str, Any], dict[str, str]]:
        """(values, errors): the submitted values converted to the settings.json types and,
        per field, the validation message from WebOverrides - the same rules as the
        environment. An unparsable rotation is an error too."""
        values: dict[str, Any] = {
            "language": form.get("language", ""),
            "quiet_hours": form.get("quiet_hours", ""),
            "clear_at": form.get("clear_at", ""),
            "update_check": form.get("update_check") == "on",
            "auto_review": form.get("auto_review", ""),
            "auto_agenda": form.get("auto_agenda", ""),
        }
        errors: dict[str, str] = {}
        rotate_raw = form.get("rotate", "").strip()
        try:
            values["rotate"] = int(rotate_raw)
        except ValueError:
            errors["rotate"] = f"must be one of {ROTATIONS}, not {rotate_raw!r}"
        for key, value in values.items():
            try:
                WebOverrides.model_validate({key: value})
            except ValidationError as exc:
                errors[key] = exc.errors()[0]["msg"].removeprefix("Value error, ")
        return values, errors

